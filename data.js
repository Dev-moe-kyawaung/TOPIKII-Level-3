function parseRows(text, keys) {
  return text.split("
").map((line, index) => {
    const parts = line.split("|");
    if (parts.length !== keys.length) {
      throw new Error(`data.js: row ${index + 1} has ${parts.length} fields`);
    }
    return Object.fromEntries(keys.map((key, i) => [key, parts[i]]));
  });
}

